// emit writes the generated seed to path.
func (g *generator) emit(path string, progressAt int64) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	w := bufio.NewWriter(f)
	defer w.Flush()

	p := &printer{w: w}

	p.line("-- Forge V2 seed data. GENERATED by `go run ./cmd/datagen` - do not edit by hand.")
	p.line("-- Source of truth: data/*.yaml and data/quotes.json.")
	p.line("PRAGMA foreign_keys=ON;")
	p.line("BEGIN;")

	// ---- subjects ----
	p.line("")
	p.line("-- GOV subjects (canonical catalogue) --")
	for _, s := range g.subjects {
		p.insert("gov_subjects", []string{"id", "name", "sort_order"},
			[]any{s.ID, s.Name, s.Order})
	}

	// ---- topics ----
	p.line("")
	p.line("-- GOV topics --")
	for _, s := range g.subjects {
		for _, t := range g.topics[s.Slug] {
			p.insert("gov_topics", []string{"id", "subject_id", "name", "sort_order"},
				[]any{t.ID, s.ID, t.Name, t.Order})
		}
	}

	// ---- lectures ----
	p.line("")
	p.line("-- GOV lectures --")
	for _, s := range g.subjects {
		for _, t := range g.topics[s.Slug] {
			for _, l := range t.Lectures {
				p.insert("gov_lectures", []string{"id", "topic_id", "title", "sort_order"},
					[]any{l.ID, t.ID, l.Title, l.Order})
			}
		}
	}

	// ---- exams ----
	p.line("")
	p.line("-- GOV exams --")
	for _, e := range g.exams {
		p.insert("gov_exams", []string{"id", "name", "sort_order"},
			[]any{e.ID, e.Name, e.Order})
	}

	// ---- exam subjects ----
	p.line("")
	p.line("-- Exam membership (which subjects belong to an exam, in exam order) --")
	for _, e := range g.exams {
		for i, se := range g.syllabus[e.ID] {
			p.insert("gov_exam_subjects", []string{"exam_id", "subject_id", "sort_order"},
				[]any{e.ID, se.Subject.ID, i + 1})
		}
	}

	// ---- syllabus ----
	p.line("")
	p.line("-- Authoritative exam syllabus (exam -> subject -> topic) --")
	for _, e := range g.exams {
		order := 0
		for _, se := range g.syllabus[e.ID] {
			for _, t := range se.Topics {
				order++
				p.insert("gov_exam_syllabus", []string{"exam_id", "subject_id", "topic_id", "sort_order"},
					[]any{e.ID, se.Subject.ID, t.ID, order})
			}
		}
	}

	// ---- exam profiles / focus / activation ----
	p.line("")
	p.line("-- Exam profiles and focus --")
	for _, e := range g.exams {
		main := 0
		if e.ID == focusExamID {
			main = 1
		}
		p.insert("gov_exam_profiles",
			[]string{"exam_id", "status", "is_main_goal", "priority", "target_date", "updated_at"},
			[]any{e.ID, "ACTIVE", main, e.Order, nil, progressAt})
	}
	p.insert("gov_focus_state", []string{"id", "focused_exam_id", "updated_at"},
		[]any{1, focusExamID, progressAt})

	p.line("")
	p.line("-- Activated subjects --")
	for _, s := range g.subjects {
		p.insert("gov_subject_activation", []string{"subject_id", "activated_at"},
			[]any{s.ID, progressAt})
	}

	// ---- routines ----
	p.line("")
	p.line("-- Practice routine: one slot per practice subject --")
	for i, slug := range []string{"subj-quant", "subj-english", "subj-reasoning"} {
		p.insert("gov_practice_routine",
			[]string{"slot_order", "duration_seconds", "selection_mode", "fixed_subject_id"},
			[]any{i + 1, 3600, "FIXED_SUBJECT", slug})
	}

	p.line("")
	p.line("-- Practice test order sessions and tests --")
	for _, spec := range g.subjects {
		for _, ses := range g.practiceSessions[spec.Slug] {
			p.insert("gov_practice_sessions",
				[]string{"id", "subject_id", "session_code", "session_order"},
				[]any{ses.ID, spec.ID, ses.Code, ses.Order})
			for _, t := range ses.Tests {
				p.insert("gov_practice_tests",
					[]string{"id", "session_id", "subject_id", "title", "sort_order"},
					[]any{t.ID, ses.ID, spec.ID, t.Title, t.Order})
			}
		}
	}

	p.line("")
	p.line("-- Practice tracks (initial cursor at session 1) --")
	for _, spec := range g.subjects {
		if len(g.practiceSessions[spec.Slug]) > 0 {
			p.insert("gov_practice_tracks",
				[]string{"subject_id", "current_session_order", "updated_at"},
				[]any{spec.ID, 1, progressAt})
		}
	}

	// ---- DSA ----
	p.line("")
	p.line("-- DSA problems --")
	for _, pr := range g.dsa {
		p.insert("dsa_problems", []string{"id", "title", "pattern", "difficulty", "sort_order"},
			[]any{pr.ID, pr.Title, pr.Pattern, pr.Difficulty, pr.Order})
	}
	p.insert("dsa_routine", []string{"id", "planned_seconds"},
		[]any{1, 9000})

	// ---- SWE ----
	p.line("")
	p.line("-- SWE areas and weekly routine --")
	for _, a := range g.sweAreas {
		p.insert("swe_areas", []string{"id", "name", "sort_order"},
			[]any{a.ID, a.Name, a.Order})
	}
	for _, s := range g.sweSlots {
		p.insert("swe_routine_slots",
			[]string{"id", "weekday", "position", "area_id", "duration_seconds"},
			[]any{s.ID, s.Weekday, s.Position, s.AreaID, s.Seconds})
	}

	// ---- quotes ----
	p.line("")
	p.line("-- Quotes --")
	for i, q := range g.quotes {
		p.insert("quotes", []string{"id", "quote", "author", "used"},
			[]any{i + 1, q.Text, q.Author, 0})
	}

	// ---- imported progress ----
	g.emitProgress(p, progressAt)

	p.line("")
	p.line("COMMIT;")
	return nil
}

// emitProgress writes the imported-progress snapshot, tasks, sessions and
// the completion/attempt rows derived from the "# done till here" markers.
func (g *generator) emitProgress(p *printer, at int64) {
	date := "2026-10-19"
	snapID := "today-" + date + "-r1"

	var done []*lecture
	for _, s := range g.subjects {
		for _, t := range g.topics[s.Slug] {
			for _, l := range t.Lectures {
				if l.complete {
					done = append(done, l)
				}
			}
		}
	}
	var attempted []*dsaProblem
	for _, pr := range g.dsa {
		if pr.attempted {
			attempted = append(attempted, pr)
		}
	}

	p.line("")
	p.line("-- Imported progress (derived from the '# done till here' markers) --")
	p.insert("today_snapshots", []string{"id", "local_date", "revision", "generated_at"},
		[]any{snapID, date, 1, at})

	govTitle := fmt.Sprintf("Imported progress markers (%d lectures + %d DSA problems; 0 sec elapsed)",
		len(done), len(attempted))
	govTaskID := "task-progress-import-gov-" + date
	dsaTaskID := "task-progress-import-dsa-" + date

	// Anchor targets: the first completed lecture and the first attempted
	// problem, so the snapshot always has a resolvable target.
	govTarget := "{}"
	if len(done) > 0 {
		govTarget = fmt.Sprintf(`{"subject_id":%q,"topic_id":%q,"lecture_id":%q}`,
			done[0].Topic.Subject.ID, done[0].Topic.ID, done[0].ID)
	}
	dsaTarget := "{}"
	if len(attempted) > 0 {
		dsaTarget = fmt.Sprintf(`{"problem_id":%q,"mode":"NEW"}`, attempted[0].ID)
	}

	p.insert("today_tasks",
		[]string{"id", "snapshot_id", "position", "scheduled_start_minute", "domain", "kind", "title", "planned_seconds", "target_json"},
		[]any{govTaskID, snapID, 1, nil, "GOV", "LECTURE", govTitle, 1, govTarget})
	p.insert("today_tasks",
		[]string{"id", "snapshot_id", "position", "scheduled_start_minute", "domain", "kind", "title", "planned_seconds", "target_json"},
		[]any{dsaTaskID, snapID, 2, nil, "DSA", "DSA", govTitle, 1, dsaTarget})
	p.insert("today_snapshot_tasks", []string{"snapshot_id", "task_id", "position"},
		[]any{snapID, govTaskID, 1})
	p.insert("today_snapshot_tasks", []string{"snapshot_id", "task_id", "position"},
		[]any{snapID, dsaTaskID, 2})

	p.insert("sessions",
		[]string{"id", "today_task_id", "domain", "kind", "title_snapshot", "target_snapshot_json", "planned_seconds", "started_at", "stopped_at", "status"},
		[]any{"sess-progress-import-gov-" + date, govTaskID, "GOV", "LECTURE", govTitle, govTarget, 1, at, at, "STOPPED"})
	p.insert("sessions",
		[]string{"id", "today_task_id", "domain", "kind", "title_snapshot", "target_snapshot_json", "planned_seconds", "started_at", "stopped_at", "status"},
		[]any{"sess-progress-import-dsa-" + date, dsaTaskID, "DSA", "DSA", govTitle, dsaTarget, 1, at, at, "STOPPED"})

	for _, l := range done {
		p.insert("gov_lecture_completions", []string{"lecture_id", "session_id", "completed_at"},
			[]any{l.ID, "sess-progress-import-gov-" + date, at})
	}
	for i, pr := range attempted {
		p.insert("dsa_attempts",
			[]string{"id", "session_id", "problem_id", "mode", "attempted_at", "independent", "optimal", "hint_used", "solve_time_seconds"},
			[]any{fmt.Sprintf("progress-import-dsa-%03d", i+1), "sess-progress-import-dsa-" + date, pr.ID, "NEW", at, 1, 1, 0, 0})
	}
}

// printer writes SQL lines.
type printer struct {
	w *bufio.Writer
}

func (p *printer) line(s string) {
	p.w.WriteString(s)
	p.w.WriteByte('\n')
}

func (p *printer) insert(table string, cols []string, vals []any) {
	var b strings.Builder
	b.WriteString("INSERT INTO ")
	b.WriteString(table)
	b.WriteString(" (")
	b.WriteString(strings.Join(cols, ", "))
	b.WriteString(") VALUES (")
	for i, v := range vals {
		if i > 0 {
			b.WriteString(", ")
		}
		switch t := v.(type) {
		case nil:
			b.WriteString("NULL")
		case string:
			b.WriteString(sqlString(t))
		case int:
			fmt.Fprintf(&b, "%d", t)
		case int64:
			fmt.Fprintf(&b, "%d", t)
		default:
			b.WriteString(sqlString(fmt.Sprint(v)))
		}
	}
	b.WriteString(");")
	p.line(b.String())
}

// sqlString renders a Go string as a single-quoted SQL literal.
func sqlString(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}
